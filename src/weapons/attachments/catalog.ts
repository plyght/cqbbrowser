export const PARTS: PartDef[] = [
  ...finishes,
  ...barrels,
  ...profiles,
  ...muzzles,
  ...handguards,
  ...mounts,
  ...slides,
  ...stocks,
  ...grips,
  ...foregrips,
  ...optics,
  ...lights,
  ...mags,
  ...slings,
];

export const PART_BY_ID: Record<string, PartDef> = Object.fromEntries(PARTS.map((p) => [p.id, p]));

/** Options for one slot on one weapon, in catalog order. */
export function partsFor(weapon: WeaponId, slot: SlotId): PartDef[] {
  return PARTS.filter((p) => p.slot === slot && p.fits.includes(weapon));
}

export function getPart<T extends PartDef = PartDef>(id: string): T {
  const p = PART_BY_ID[id];
  if (!p) throw new Error(`unknown part '${id}'`);
  return p as T;
}
